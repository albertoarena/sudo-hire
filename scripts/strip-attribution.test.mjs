import { describe, expect, it } from 'vitest';
import { stripAttribution } from './strip-attribution.mjs';

const body = '## Changes\n\n- One change.\n\n## Review\n\nTests: 95 passed.';

describe('stripAttribution', () => {
    it('removes the footer of a cloud session', () => {
        const withFooter = `${body}\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_example)_\n`;

        expect(stripAttribution(withFooter)).toBe(body);
    });

    it('removes the footer of the command line', () => {
        const withFooter = `${body}\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)`;

        expect(stripAttribution(withFooter)).toBe(body);
    });

    it('leaves a body without a footer unchanged', () => {
        expect(stripAttribution(body)).toBe(body);
    });

    it('keeps a separator in the middle of the body', () => {
        const withRule = '## Changes\n\n---\n\n## Review';

        expect(stripAttribution(withRule)).toBe(withRule);
    });

    it('keeps normal text that names the tool', () => {
        const text = `${body}\n\nThe job asks for Claude Code experience.`;

        expect(stripAttribution(text)).toBe(text);
    });

    it('gives an empty string for an empty body', () => {
        expect(stripAttribution(null)).toBe('');
        expect(stripAttribution('')).toBe('');
    });
});
